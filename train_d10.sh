#!/usr/bin/env bash
# One d10-era variant per invocation, pinned to one GPU. Two of these run at a time
# (GPU=0 and GPU=1); waves are sequenced by the caller, never by this file.
#
# d9  = data/lerobot_v3_d9_0912   242 ep / 54,686 f / 18 tasks -- the 0912 recording:
#       CAMERAS MOVED, start and end pose unified (the arm parks home and holds still for
#       ~2.4 s at the end), one recorder (SEOK3), place-only. Still ONE object per scene,
#       so it adds no noun-grounding signal. One dead take was dropped before conversion.
# d10 = data/lerobot_v3_d10_merged 1970 ep / 258,051 f / 54 tasks = d8 (1728) + d9 (242).
#       Merge appends, so episodes [0, 1728) are the OLD camera rig and [1728, 1970) the new
#       one. That index is the --old-episode-boundary below.
#
# Variants
#   new    d9 ONLY, no augmentation         -- the new rig on its own
#   mix    d10, old episodes weighted 0.3   -- everything, with the old rig turned down
#
# Why 0.3 and not a merge-time subsample: --old-episode-weight keeps ALL the old episodes and
# redraws which 30% of their frames each epoch contains, so the old data keeps its variety and
# loses only its influence. See _attach_source_weight in train_smolvla_openmani.py.
#
# STEPS: `new` gets 6000 at batch 32 = 192k samples = 3.5 epochs of d9 (it is small).
# `mix` gets 8000 = 256k samples; with the 0.3 weight an epoch is 1728-era frames x0.3 plus
# all of d9, so ~1.9 epochs. Neither is compute-matched to the other ON PURPOSE -- they answer
# different questions and their eval_losses are NOT comparable (different held-out sets).
#
# Do NOT edit this file while it runs -- bash reads a script by byte offset (2026-08-29).
#
#   GPU=0 ./train_d10.sh new
set -u
cd "$(dirname "$0")"

V=${1:?usage: GPU=<n> ./train_d10.sh <new|mix>}
GPU=${GPU:-0}
SAVE_FREQ=250; EVAL_STEPS=250; WORKERS=3; BATCH=32
EVAL_MODE=random; EVAL_SEED=0
OLD_W=1.0; OLD_SEED=0

case "$V" in
  new) DS=data/lerobot_v3_d9_0912;    EVAL_EPISODES=18; BOUNDARY=0;    FLAGS=""
       STEPS=${STEPS:-6000} ;;
  mix) DS=data/lerobot_v3_d10_merged; EVAL_EPISODES=40; BOUNDARY=1728; OLD_W=0.3
       FLAGS="--old-episode-weight 0.3 --old-episode-boundary 1728 --old-episode-seed 0"
       STEPS=${STEPS:-8000} ;;
  *) echo "unknown variant $V"; exit 2 ;;
esac
meaning () {
  case "$V" in
    new) echo "d9 ONLY (242 ep, new camera rig, unified start/end), no augmentation" ;;
    mix) echo "d10 (1970 ep) with episodes [0,1728) -- the old rig -- weighted 0.3" ;;
  esac
}

OUT=runs/d10_${V}; LOG=runs/d10_${V}.log; MANIFEST=runs/d10_${V}.manifest.json
[ -d "$OUT" ] && { echo "skip d10_${V}: $OUT exists"; exit 0; }
[ -d "$DS" ]  || { echo "missing dataset $DS"; exit 2; }
echo "[$(date +%T)] === d10_${V} on GPU$GPU: $(meaning) ==="

DROP_P=0; SMOOTH_W=0
/home/vcl/anaconda3/envs/lerobot/bin/python - "$MANIFEST" "$V" "$DROP_P" "$SMOOTH_W" "$(meaning)" <<EOF
import hashlib, json, subprocess, sys, time
from pathlib import Path
out, V, drop_p, smooth_w, meaning = Path(sys.argv[1]), sys.argv[2], float(sys.argv[3]), float(sys.argv[4]), sys.argv[5]
out.parent.mkdir(parents=True, exist_ok=True)
def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:12] if Path(p).is_file() else None
info = json.loads(Path("$DS/meta/info.json").read_text())
om = Path("$DS/openmani_meta.json")
om = json.loads(om.read_text()) if om.is_file() else {}
out.write_text(json.dumps({
    "run": f"d10_{V}", "variant": V, "variant_meaning": meaning, "gpu": $GPU,
    "started_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    "dataset_root": "$DS", "dataset_episodes": info["total_episodes"],
    "dataset_frames": info["total_frames"], "dataset_tasks": info["total_tasks"],
    "action_dim": info["features"]["action"]["shape"][0],
    "action_names": info["features"]["action"].get("names"),
    "done_flag_lead": om.get("termination_channels", {}).get("done_flag_lead"),
    "smooth_loss_max_channel": 5,
    "source_boundary": $BOUNDARY,
    "old_episode_weight": $OLD_W, "old_episode_seed": $OLD_SEED,
    "old_episode_weight": $OLD_W, "old_episode_seed": $OLD_SEED,
    "base_policy": "lerobot/smolvla_base",
    "steps": $STEPS, "batch_size": $BATCH, "num_workers": $WORKERS,
    "epochs": round($STEPS * $BATCH / info["total_frames"], 3),
    "chunk_size": 16, "n_action_steps": 8, "seed": 1000,
    "expected_evals": $STEPS // $EVAL_STEPS,
    "eval_split": 0.05, "eval_split_mode": "$EVAL_MODE",
    "eval_split_seed": $EVAL_SEED, "eval_episodes": $EVAL_EPISODES,
    "camera_dropout_p": drop_p, "camera_dropout_fill": "gray" if drop_p else None,
    "smooth_loss_weight": smooth_w, "smooth_loss_order": 1 if smooth_w else 0,
    "code_sha256_12": {f: sha(f) for f in
                       ["train_smolvla_openmani.py", "train_d10.sh", "verify_run.py",
                        "prune_watchdog.py"]},
    "git_lerobot": subprocess.run(["git", "-C", "lerobot", "rev-parse", "--short", "HEAD"],
                                  capture_output=True, text=True).stdout.strip() or None,
}, indent=2))
print("manifest ->", out)
EOF

/home/vcl/anaconda3/envs/lerobot/bin/python -u prune_watchdog.py \
  --run-dir "$OUT" --interval 120 >> runs/d10_${V}.watchdog.log 2>&1 &
WD=$!

CUDA_VISIBLE_DEVICES=$GPU conda run --no-capture-output -n lerobot \
  python train_smolvla_openmani.py \
    --policy.path=lerobot/smolvla_base --policy.push_to_hub=false \
    --dataset.root=$DS --dataset.repo_id=local/openmani_d10_${V} \
    --dataset.eval_split=0.05 --eval-split-mode $EVAL_MODE --eval-split-seed $EVAL_SEED \
    --eval-episodes $EVAL_EPISODES \
    --steps $STEPS --save_freq $SAVE_FREQ --eval_steps $EVAL_STEPS --log_freq 250 --seed 1000 \
    --num_workers $WORKERS --batch_size $BATCH \
    --policy.chunk_size=16 --policy.n_action_steps=8 \
    --policy.freeze_vision_encoder=false --policy.train_expert_only=false \
    $FLAGS \
    --output_dir=$OUT --job_name=d10_${V} --diag-out $OUT/probe.jsonl \
    > "$LOG" 2>&1
RC=$?
wait $WD 2>/dev/null || true
[ -d "$OUT" ] && cp -f "$MANIFEST" "$OUT/run_manifest.json"

# the exit code is not the judge (conda run has returned 0 over a dead child): the log is
echo "[$(date +%T)] d10_${V} finished rc=$RC eval_lines=$(grep -c 'eval_loss=' "$LOG")"
conda run --no-capture-output -n lerobot \
  python verify_run.py --run-dir "$OUT" --log "$LOG" --json-out "$OUT/verify.json" \
  2>&1 | sed "s/^/  [verify $V] /"
if [ "${PIPESTATUS[0]}" -ne 0 ]; then
  echo "[$(date +%T)] d10_${V}: verification FAILED -- keeping every checkpoint"; exit 1
fi
conda run --no-capture-output -n lerobot \
  python prune_checkpoints.py --run-dir "$OUT" --log "$LOG" --keep-last \
  2>&1 | sed "s/^/  [prune $V] /"
echo "[$(date +%T)] d10_${V}: kept $(ls "$OUT/checkpoints" | tr '\n' ' ')"
