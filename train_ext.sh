#!/usr/bin/env bash
# 2026-10-11 smolvla_ext variants (PVI / Coda / ROCKET), recipe = d10_new:
#   d9_0912, lr 1e-4, 6000 steps, batch 32, workers 3, seed 1000, chunk 16/8, VLM + SigLIP trained
#   (freeze_vision_encoder=false, train_expert_only=false), same 18 pinned eval episodes,
#   no state noise, no loss weights, no relabel. eval_loss = main-AE flow loss only (comparable).
#   VLM / SigLIP / connector / state_proj ('rest' group = optimizer_lr): 1e-4 for the web start (R CW RC),
#   1e-5 for the d10_new start (already converged; user 2026-10-11). Cosine floor kept at 2.5% of peak
#   (scheduler_decay_lr 2.5e-6 / 2.5e-7). New modules always 1e-4, main AE 1e-5 in the L variants.
#   R    ROCKET              start smolvla_base  main AE 1e-4   pairs 3:4,7:11,11:17,15:23  alpha 0.125
#   PF   PVI                 start d10_new 4750  main AE frozen   new modules 1e-4
#   PL   PVI                 start d10_new 4750  main AE 1e-5
#   CF   Coda                start d10_new 4750  main AE frozen   5 main + 5 correction steps
#   CL   Coda                start d10_new 4750  main AE 1e-5
#   CW   Coda                start smolvla_base  main AE 1e-4
#   RC   ROCKET + Coda       start smolvla_base  main AE 1e-4
#   PCF  PVI + Coda          start d10_new 4750  main AE frozen   (PVI injections go to the main AE only)
#   PCL  PVI + Coda          start d10_new 4750  main AE 1e-5
# 2026-10-11 (87-run matrix): a run is a SPEC instead of a fixed name.
#   MODS  = subset of R P C in that order (R, P, C, RP, RC, PC, RPC)
#   START = F (d10_new 4750, main AE frozen) | L (d10_new, main AE 1e-5) | W (smolvla_base, main AE 1e-4)
#   RL    = u (VLM inputs 3,7,11,15 = evenly spaced) | e (inputs 1,2,3,4 = outputs of the working layers 0-3)
#   RA    = ROCKET alpha (0.125 | 0.5)          CS = Coda steps, main = correction (5 | 10)
#   rest group (VLM / SigLIP / connector / state_proj) LR: 1e-4 if ROCKET or web start, else 1e-5;
#   cosine floor = 2.5% of that peak (scheduler_decay_lr). VGGT teacher layers 4,11,17,23 always.
#   tag = ext_<MODS>_<START>[_R<RL>_a<RA w/o dot>][_c<CS>]   e.g. ext_RPC_L_Ru_a05_c10
# Usage:  GPU=0 MODS=RC START=W RL=e RA=0.5 CS=10 ./train_ext.sh       (spec)
#         GPU=0 ./train_ext.sh PF                                       (old names, same as before)
# Smoke:  GPU=1 STEPS=20 SAVE_FREQ=20 EVAL_STEPS=20 LOG_FREQ=10 TAGPREFIX=smoke_ext_ ./train_ext.sh PF
#         --dry-run as $1 (or DRY=1) prints tag + flags and exits.
# Do NOT edit this file while it runs -- bash reads a script by byte offset (2026-08-29).
set -u
cd "$(dirname "$0")"
VAR=${1:-}
[ "$VAR" = "--dry-run" ] && { DRY=1; VAR=${2:-}; }
DRY=${DRY:-0}
GPU=${GPU:-0}; STEPS=${STEPS:-6000}
# eval + checkpoint every 1000 steps (user 2026-10-12; was 250)
SAVE_FREQ=${SAVE_FREQ:-1000}; EVAL_STEPS=${EVAL_STEPS:-1000}; LOG_FREQ=${LOG_FREQ:-250}
WORKERS=3; BATCH=32; EVAL_MODE=random; EVAL_SEED=0
TAGPREFIX=${TAGPREFIX:-ext_}
DS=data/lerobot_v3_d9_0912
BASE=lerobot/smolvla_base
D10=runs/d10_new/checkpoints/004750/pretrained_model
# int8 NVMe copy (smolvla_ext.quantize_targets, 2026-10-11); fp16 original: /media/vcl/DATA2/vla_vggt/d9_0912_L4-11-17-23
ROCKET_TARGETS=${ROCKET_TARGETS:-data/vla_vggt/d9_0912_L4-11-17-23_int8}
MAIN_LR=1e-5; NEW_LR=1e-4
# speed (user 2026-10-11: compile + fused attention on): smolvla_ext/fast.py
EXT_ATTN=${EXT_ATTN:-sdpa}; EXT_COMPILE=${EXT_COMPILE:-layers}
D9_EVAL_IDX="4,15,23,29,42,45,61,64,78,84,100,110,128,137,172,198,230,237"

# old fixed names -> the same spec (tags unchanged: ext_<NAME>)
case "$VAR" in
  "")  ;;
  R)   MODS=R;  START=W ;;
  PF)  MODS=P;  START=F ;;
  PL)  MODS=P;  START=L ;;
  CF)  MODS=C;  START=F ;;
  CL)  MODS=C;  START=L ;;
  CW)  MODS=C;  START=W ;;
  RC)  MODS=RC; START=W ;;
  PCF) MODS=PC; START=F ;;
  PCL) MODS=PC; START=L ;;
  *) echo "unknown variant $VAR"; exit 2 ;;
esac
MODS=${MODS:?set MODS (R P C RP RC PC RPC) or give an old variant name}
START=${START:?set START (F L W)}
RL=${RL:-u}; RA=${RA:-0.125}; CS=${CS:-5}
case "$MODS" in R|P|C|RP|RC|PC|RPC) ;; *) echo "bad MODS=$MODS"; exit 2 ;; esac
PVI=0; CODA=0; ROCKET=0
[[ $MODS == *R* ]] && ROCKET=1
[[ $MODS == *P* ]] && PVI=1
[[ $MODS == *C* ]] && CODA=1
case "$START" in
  F) POL=$D10;  MAIN=freeze ;;
  L) POL=$D10;  MAIN=lr ;;
  W) POL=$BASE; MAIN=train ;;
  *) echo "bad START=$START"; exit 2 ;;
esac
case "$RL" in u) PAIRS="3:4,7:11,11:17,15:23" ;; e) PAIRS="1:4,2:11,3:17,4:23" ;; *) echo "bad RL=$RL"; exit 2 ;; esac
case "$RA" in 0.125|0.5) ;; *) echo "bad RA=$RA"; exit 2 ;; esac
case "$CS" in 5|10) ;; *) echo "bad CS=$CS"; exit 2 ;; esac
ALPHA=$RA; CODA_STEPS=$CS
if [ $ROCKET = 1 ] || [ "$START" = W ]; then LR=1e-4; DECAY=2.5e-6; else LR=1e-5; DECAY=2.5e-7; fi
NUM_STEPS=10; [ $CODA = 1 ] && NUM_STEPS=$CS
EXTF="--ext-main-ae $MAIN --ext-main-ae-lr $MAIN_LR --ext-new-lr $NEW_LR --ext-attn $EXT_ATTN --ext-compile $EXT_COMPILE"
[ $PVI = 1 ] && EXTF="$EXTF --ext-pvi"
[ $CODA = 1 ] && EXTF="$EXTF --ext-coda --ext-coda-steps $CODA_STEPS --policy.num_steps=$CS"
[ $ROCKET = 1 ] && EXTF="$EXTF --ext-rocket --ext-rocket-targets $ROCKET_TARGETS --ext-rocket-pairs $PAIRS --ext-rocket-alpha $ALPHA --prefetch_factor=2"
if [ -n "$VAR" ]; then TAG=${TAGPREFIX}${VAR}
else TAG=${TAGPREFIX}${MODS}_${START}
  [ $ROCKET = 1 ] && TAG=${TAG}_R${RL}_a${RA/./}
  [ $CODA = 1 ] && TAG=${TAG}_c${CS}
fi
FLAGS="--eval-episode-indices $D9_EVAL_IDX --policy.optimizer_lr=$LR --policy.scheduler_decay_lr=$DECAY $EXTF ${EXTRA:-}"
MEAN="ext ${VAR:-$MODS/$START}: pvi=$PVI coda=$CODA rocket=$ROCKET main_ae=$MAIN rest_lr=$LR start=$POL$([ $ROCKET = 1 ] && echo " pairs=$PAIRS alpha=$ALPHA")$([ $CODA = 1 ] && echo " coda=$CS+$CS") (recipe d10_new, no noise, no loss weights)"
if [ "$DRY" = 1 ]; then echo "$TAG | $MEAN | $FLAGS"; exit 0; fi
# input checks after the dry-run exit: the chain derives tags with DRY=1 even before the inputs exist
if [ $ROCKET = 1 ] && [ ! -f "$ROCKET_TARGETS/meta.json" ]; then
  echo "ROCKET targets missing: $ROCKET_TARGETS/meta.json (run python -m smolvla_ext.rocket first)"; exit 2
fi
if [ "$POL" = "$D10" ] && [ ! -f "$D10/model.safetensors" ]; then
  echo "start checkpoint missing: $D10"; exit 2
fi

OUT=runs/$TAG; LOG=runs/$TAG.log; MANIFEST=runs/$TAG.manifest.json
[ -d "$OUT" ] && { echo "skip $TAG: $OUT exists"; exit 0; }
echo "[$(date +%T)] === $TAG on GPU$GPU: $MEAN ==="
export DS POL STEPS BATCH FLAGS GPU WORKERS EVAL_STEPS EVAL_MODE EVAL_SEED LR TAG MEAN
export PVI CODA ROCKET MAIN MAIN_LR NEW_LR CODA_STEPS PAIRS ALPHA ROCKET_TARGETS D10 MODS START RL RA CS DECAY NUM_STEPS EXT_ATTN EXT_COMPILE
/home/vcl/anaconda3/envs/lerobot/bin/python - "$MANIFEST" <<'EOF'
import glob, hashlib, json, os, subprocess, sys, time
from pathlib import Path
out = Path(sys.argv[1]); E = os.environ
def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:12] if Path(p).is_file() else None
info = json.loads(Path(E["DS"], "meta/info.json").read_text())
F = E["FLAGS"]
coda = E["CODA"] == "1"; rocket = E["ROCKET"] == "1"
ext = {"pvi": E["PVI"] == "1", "coda": coda, "rocket": rocket, "main_ae": E["MAIN"],
       "main_ae_lr": float(E["MAIN_LR"]), "new_lr": float(E["NEW_LR"]),
       "attn_impl": E["EXT_ATTN"], "compile_mode": E["EXT_COMPILE"]}
if coda:
    ext.update(coda_num_steps=int(E["CODA_STEPS"]), main_num_steps=int(E["CS"]))
if rocket:
    ext.update(rocket_pairs=E["PAIRS"], rocket_alpha=float(E["ALPHA"]), rocket_target_dir=E["ROCKET_TARGETS"])
files = ["train_smolvla_openmani.py", "train_ext.sh", "verify_run.py", "prune_watchdog.py"] + \
        sorted(glob.glob("smolvla_ext/*.py"))
out.write_text(json.dumps({
    "run": E["TAG"], "variant_meaning": E["MEAN"], "gpu": E["GPU"],
    "started_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    "dataset_root": E["DS"], "dataset_episodes": info["total_episodes"],
    "dataset_frames": info["total_frames"], "dataset_tasks": info["total_tasks"],
    "action_dim": info["features"]["action"]["shape"][0],
    "base_policy": E["POL"], "optimizer_lr": float(E["LR"]),
    "is_sequential_finetune": E["POL"] == E["D10"],
    "steps": int(E["STEPS"]), "batch_size": int(E["BATCH"]), "num_workers": int(E["WORKERS"]),
    "epochs": round(int(E["STEPS"]) * int(E["BATCH"]) / info["total_frames"], 3),
    "chunk_size": 16, "n_action_steps": 8, "seed": 1000,
    "num_steps": int(E["NUM_STEPS"]), "scheduler_decay_lr": float(E["DECAY"]),
    "spec": {"mods": E["MODS"], "start": E["START"], "rl": E["RL"] if rocket else None,
             "ra": float(E["RA"]) if rocket else None, "cs": int(E["CS"]) if coda else None},
    "expected_evals": int(E["STEPS"]) // int(E["EVAL_STEPS"]),
    "eval_split": 0.05, "eval_split_mode": E["EVAL_MODE"], "eval_split_seed": int(E["EVAL_SEED"]),
    "flags": F, "camera_dropout_p": 0.0, "state_noise_p": 0.0, "state_noise_sigma": 0.0,
    "gripper_goal_relabel": False, "smooth_loss_weight": 0.0,
    "ext": ext,
    "code_sha256_12": {f: sha(f) for f in files},
    "git_lerobot": subprocess.run(["git", "-C", "lerobot", "rev-parse", "--short", "HEAD"],
                                  capture_output=True, text=True).stdout.strip() or None,
}, indent=2))
print("manifest ->", out)
EOF
/home/vcl/anaconda3/envs/lerobot/bin/python -u prune_watchdog.py \
  --run-dir "$OUT" --interval 120 >> runs/$TAG.watchdog.log 2>&1 &
WD=$!
PYTHONPATH="$PWD${PYTHONPATH:+:$PYTHONPATH}" CUDA_VISIBLE_DEVICES=$GPU conda run --no-capture-output -n lerobot \
  python train_smolvla_openmani.py \
    --policy.path=$POL --policy.push_to_hub=false \
    --dataset.root=$DS --dataset.repo_id=local/openmani_$TAG \
    --dataset.eval_split=0.05 --eval-split-mode $EVAL_MODE --eval-split-seed $EVAL_SEED \
    --steps $STEPS --save_freq $SAVE_FREQ --eval_steps $EVAL_STEPS --log_freq $LOG_FREQ --seed 1000 \
    --num_workers $WORKERS --batch_size $BATCH \
    --policy.chunk_size=16 --policy.n_action_steps=8 \
    --policy.freeze_vision_encoder=false --policy.train_expert_only=false \
    $FLAGS \
    --output_dir=$OUT --job_name=$TAG --diag-out $OUT/probe.jsonl \
    > "$LOG" 2>&1
RC=$?
wait $WD 2>/dev/null || true
[ -d "$OUT" ] && cp -f "$MANIFEST" "$OUT/run_manifest.json"
echo "[$(date +%T)] $TAG finished rc=$RC eval_lines=$(grep -c 'eval_loss=' "$LOG") ext_loss_lines=$(grep -c '\[ext\] losses' "$LOG")"
# direct interpreter (not conda run): the exit code gates the pruning below
/home/vcl/anaconda3/envs/lerobot/bin/python verify_run.py --run-dir "$OUT" --log "$LOG" --json-out "$OUT/verify.json" \
  2>&1 | sed "s/^/  [verify $TAG] /"
if [ "${PIPESTATUS[0]}" -ne 0 ]; then
  echo "[$(date +%T)] $TAG: verification FAILED -- keeping every checkpoint"; exit 1
fi
/home/vcl/anaconda3/envs/lerobot/bin/python prune_checkpoints.py --run-dir "$OUT" --log "$LOG" --keep-last \
  2>&1 | sed "s/^/  [prune $TAG] /"
echo "[$(date +%T)] $TAG: kept $(ls "$OUT/checkpoints" | tr '\n' ' ')"
